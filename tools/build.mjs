// Build: bundles src/ (three.js + addons) into ONE classic script (js/game.bundle.js) so index.html works via file://
// and embeds the CC0 sound samples (sounds/*.mp3) as base64 into js/sounds-src.js (decoded with decodeAudioData).
// Usage: npm install && node tools/build.mjs
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'fs';
import { dirname, resolve } from 'path';
import { fileURLToPath } from 'url';
import { build } from 'esbuild';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
await build({
  entryPoints: [resolve(root, 'src/entry.js')],
  bundle: true, format: 'iife', minify: true,
  target: ['es2020', 'safari15'],
  outfile: resolve(root, 'js/game.bundle.js'),
  legalComments: 'eof',
  banner: { js: '/* Haunted Mansion Escape — bundled with three.js (MIT, (c) 2010-2026 three.js authors) */' }
});
const dir = resolve(root, 'sounds');
const obj = {}; let bytes = 0;
if (existsSync(dir)) for (const f of readdirSync(dir).filter(f => f.endsWith('.mp3')).sort()) {
  const b = readFileSync(resolve(dir, f)); bytes += b.length; obj[f.replace(/\.mp3$/, '')] = b.toString('base64');
}
writeFileSync(resolve(root, 'js/sounds-src.js'), '/* generated by tools/build.mjs — CC0 samples, see LICENSES/SOUNDS.md */\nwindow.HME_SOUNDS = ' + JSON.stringify(obj) + ';\n');
console.log('built js/game.bundle.js + js/sounds-src.js (' + Object.keys(obj).length + ' sounds, ' + Math.round(bytes / 1024) + ' KB mp3)');
